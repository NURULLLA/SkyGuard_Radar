def airport_city(iata):
    """Just the city: "Бахрейн". Falls back to the code itself."""
    if not iata or iata in ("—", ""):
        return "—"
    code = iata.strip().upper()
    return NAMES_RU.get(code) or NAMES.get(code) or code


def airport_name(iata):
    """City and code together: "Бахрейн (BAH)"."""
    if not iata or iata in ("—", ""):
        return "—"
    code = iata.strip().upper()
    city = NAMES_RU.get(code) or NAMES.get(code)
    return f"{city} ({code})" if city else code
