def airport_name(iata):
    """"Дубай (DWC)" when known, otherwise just the code."""
    if not iata or iata in ("—", "", None):
        return "—"
    hit = AIRPORTS.get(iata.upper())
    return f"{hit[0]} ({iata.upper()})" if hit else iata.upper()


def airport_country(iata):
    hit = AIRPORTS.get((iata or "").upper())
    return hit[1] if hit else ""
